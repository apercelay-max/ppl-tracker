const ACCENTS: Record<string, string[]> = {
  '́': ['00010', '00100'], // aigu
  '̀': ['01000', '00100'], // grave
  '̂': ['00100', '01010'], // circonflexe
  '̈': ['00000', '01010'], // tréma
};

export interface DotLayout {
  /** Points allumés, en cases de la grille (x vers la droite, y vers le bas). */
  dots: { x: number; y: number }[];
  cols: number;
  rows: number;
}

/** Rangées de la grille : 2 d'accents, 7 de lettre, 1 de queue (virgule, cédille). */
export const DOT_ROWS = 10;

export function layoutText(text: string): DotLayout {
  const items: { glyph: string[]; x: number; accent: string[] | null; cedilla: boolean }[] = [];
  let x = 0;
  for (const ch of text.toLocaleUpperCase('fr').normalize('NFD')) {
    const cp = ch.codePointAt(0) ?? 0;
    if (cp >= 0x300 && cp <= 0x36f) {
      // Signe combinant : il se pose sur la lettre précédente.
      const last = items[items.length - 1];
      if (last) {
        if (cp === 0x327) last.cedilla = true;
        else if (ACCENTS[ch]) last.accent = ACCENTS[ch];
      }
      continue;
    }
    if (ch === ' ') { x += 3; continue; }
    items.push({ glyph: GLYPHS[ch] ?? GLYPHS['?'], x, accent: null, cedilla: false });
    x += 6;
  }
  const dots: { x: number; y: number }[] = [];
  for (const it of items) {
    it.glyph.forEach((row, r) => { for (let c = 0; c < 5; c++) if (row[c] === '1') dots.push({ x: it.x + c, y: 2 + r }); });
    it.accent?.forEach((row, r) => { for (let c = 0; c < 5; c++) if (row[c] === '1') dots.push({ x: it.x + c, y: r }); });
    if (it.cedilla) dots.push({ x: it.x + 2, y: 9 });
  }
  return { dots, cols: Math.max(1, x - 1), rows: DOT_ROWS };
}
